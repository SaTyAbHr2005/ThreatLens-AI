"""Incident dossier (Markdown) and OCSF export for SIEMs."""

from threatlens import __version__
from threatlens.core.schemas import SIGNAL_NAMES, ActionEvent, Alert, Decision


def dossier_markdown(alert: Alert, decisions: list[Decision], events: list[ActionEvent]) -> str:
    lines = [
        f"# Incident {alert.id}",
        "",
        f"**Agent:** {alert.agent_id}  ",
        f"**Risk:** {alert.risk:.0f} / 100 (band: {alert.tier.value.replace('_', '-')}) · "
        f"**Containment applied:** {alert.containment.value.replace('_', '-') if alert.containment else 'none'}  ",
        f"**Status:** {alert.status.value}" + (f" · **Feedback:** {alert.feedback.value}" if alert.feedback else "") + "  ",
        f"**Raised:** {alert.ts.isoformat()} · **Last update:** {alert.updated_at.isoformat()}",
        "",
        "## What happened",
        "",
        alert.narrative or alert.headline,
        "",
    ]
    if alert.decoded_injection:
        lines += ["## Hidden instruction found in the source content", "", "```text",
                  alert.decoded_injection, "```", ""]
    if alert.counterfactual:
        lines += [f"> {alert.counterfactual}", ""]
    lines += ["## Why it scored this risk", "", "| Share | Factor |", "|---:|---|"]
    lines += [f"| {f.contribution:.0%} | {f.evidence} |" for f in alert.factors]
    lines += ["", "## Actions taken", ""]
    lines += [f"- {a}" for a in alert.actions_taken] or ["- None yet."]
    if decisions:
        lines += ["", "## Containment decisions", "", "| Time | From → To | By | Reason |", "|---|---|---|---|"]
        lines += [f"| {d.ts.isoformat()} | {(d.from_status.value if d.from_status else '?')} → "
                  f"{(d.to_status.value if d.to_status else '?')} | {d.actor} | {d.reason} |" for d in decisions]
    if events:
        lines += ["", "## Timeline", "", "| Time | Action | Risk | Decision |", "|---|---|---:|---|"]
        lines += [f"| {e.ts.isoformat()} | {e.action.tool} {e.action.resource or ''} | "
                  f"{(e.risk if e.risk is not None else 0):.0f} | {e.decision.value if e.decision else ''} |"
                  for e in events]
    lines += ["", "## Matches known threat patterns", ""]
    lines += [f"- {f}" for f in alert.frameworks] or ["- None."]
    lines += ["", "## Recommended next steps", ""]
    lines += [f"- {r}" for r in alert.recommendations]
    lines += ["", "## All signals for the alerting action", "", "| Signal | Score |", "|---|---:|"]
    lines += [f"| {SIGNAL_NAMES[s]} | {v:.2f} |" for s, v in sorted(alert.scores.items(), key=lambda kv: kv[0].value)]
    lines += ["", f"_Generated by ThreatLens AI {__version__}._", ""]
    return "\n".join(lines)


def _severity(risk: float) -> tuple[int, str]:
    if risk >= 90:
        return 5, "Critical"
    if risk >= 75:
        return 4, "High"
    if risk >= 60:
        return 3, "Medium"
    if risk >= 40:
        return 2, "Low"
    return 1, "Informational"


def ocsf_finding(alert: Alert) -> dict:
    """OCSF 1.x Detection Finding (class_uid 2004), ready for Splunk / Sentinel / Elastic."""
    sev_id, sev = _severity(alert.risk)
    return {
        "class_uid": 2004,
        "class_name": "Detection Finding",
        "category_uid": 2,
        "category_name": "Findings",
        "activity_id": 1,
        "activity_name": "Create",
        "type_uid": 200401,
        "time": int(alert.ts.timestamp() * 1000),
        "severity_id": sev_id,
        "severity": sev,
        "status": alert.status.value,
        "risk_score": round(alert.risk),
        "message": alert.narrative or alert.headline,
        "finding_info": {
            "uid": alert.id,
            "title": f"AI agent identity drift: {alert.agent_id}",
            "desc": alert.headline,
            "types": alert.frameworks,
            "created_time": int(alert.ts.timestamp() * 1000),
            "modified_time": int(alert.updated_at.timestamp() * 1000),
        },
        "actor": {"user": {"uid": alert.agent_id, "type": "AI agent"}},
        "evidences": [{"data": {"signal": f.signal.value, "share": f.contribution, "evidence": f.evidence}}
                      for f in alert.factors],
        "remediation": {"desc": " ".join(alert.recommendations)},
        "unmapped": {"cause_content_id": alert.cause_content_id, "counterfactual": alert.counterfactual,
                     "actions_taken": alert.actions_taken},
        "metadata": {"version": "1.1.0", "product": {"name": "ThreatLens AI", "vendor_name": "ThreatLens",
                                                     "version": __version__}},
    }
